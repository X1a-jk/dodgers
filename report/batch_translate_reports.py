def translate_html(html):
    # 1. 短语替换（区分大小写，保留括号内英文的翻译场景）
    for en, zh in PHRASES.items():
        html = html.replace(en, zh)

    # 2. 带词边界的正则替换
    for pattern, repl in WORD_PAIRS.items():
        html = re.sub(pattern, repl, html, flags=re.IGNORECASE)

    # 3. 修正常见连续空格
    html = re.sub(r'  +', ' ', html)
    return html


def main():
    count = 0
    for slug in os.listdir(BASE_DIR):
        dir_path = os.path.join(BASE_DIR, slug)
        if not os.path.isdir(dir_path):
            continue
        html_files = [f for f in os.listdir(dir_path) if f.endswith('-scouting-report.html')]
        for fname in html_files:
            path = os.path.join(dir_path, fname)
            with open(path, 'r', encoding='utf-8') as f:
                html = f.read()
            new_html = translate_html(html)
            if new_html != html:
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(new_html)
                count += 1
                print(f'[translated] {path}')
    print(f'\nTranslated {count} reports.')


if __name__ == '__main__':
    main()
